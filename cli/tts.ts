import { mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { firmwareAudio } from './audio';

const image = 'microbit-tts:local';
const bootstrap = 'microbit-tts-bootstrap:local';
type Command = (argv: string[], capture?: boolean) => Promise<string>;
const recipeFiles = ['toolchain/tts/Dockerfile', 'toolchain/tts/versions.json', 'toolchain/tts/requirements.lock',
  'toolchain/tts/assets.json', 'toolchain/tts/fetch.py', 'toolchain/tts/synthesize.py', 'toolchain/versions.json'];

async function recipeHash(root: string) {
  const hash = createHash('sha256');
  for (const file of recipeFiles) hash.update(file).update(await readFile(join(root, file)));
  return hash.digest('hex');
}

/** pip --report JSON -> hash-locked direct-URL requirements; rejects CUDA and unhashed artifacts. */
export function lockFromReport(report: any) {
  const lines = (report.install as any[]).map(entry => {
    const name: string = entry.metadata.name.toLowerCase().replace(/[-_.]+/g, '-');
    const url: string = entry.download_info.url;
    const sha = entry.download_info.archive_info?.hashes?.sha256
      ?? entry.download_info.archive_info?.hash?.match(/^sha256=([a-f0-9]{64})$/)?.[1];
    if (!/^[a-f0-9]{64}$/.test(sha ?? '')) throw new Error(`No SHA-256 for ${name}`);
    if (!url.startsWith('https://')) throw new Error(`Non-HTTPS artifact for ${name}`);
    if (/^nvidia-|^triton$/.test(name) || /\+cu\d+/.test(entry.metadata.version)) throw new Error(`CUDA dependency ${name} in CPU lock`);
    return `${name} @ ${url} --hash=sha256:${sha}`;
  }).sort();
  if (!(report.install as any[]).some(e => e.metadata.name.toLowerCase() === 'torch' && /\+cpu$/.test(e.metadata.version))) {
    throw new Error('Lock lacks a CPU-only torch wheel');
  }
  return '# Generated by run tts lock from requirements.in. Do not edit.\n' + lines.join('\n') + '\n';
}

export function ttsArgs(root: string, network: 'none' | 'bridge') {
  return ['--rm', '--init', '--user', `${process.getuid!()}:${process.getgid!()}`,
    '--network', network, '--cap-drop=ALL', '--security-opt=no-new-privileges', '--read-only',
    '--pids-limit', '256', '--memory', '4g', '--cpus', '4',
    '--tmpfs', '/tmp:rw,nosuid,nodev,size=3g', '-e', 'HOME=/tmp/home', '-e', 'TMPDIR=/tmp',
    '-e', 'XDG_CACHE_HOME=/tmp/cache'];
}

async function buildArgs(root: string, target: 'bootstrap' | 'tts') {
  const v = JSON.parse(await readFile(join(root, 'toolchain/tts/versions.json'), 'utf8'));
  const chain = JSON.parse(await readFile(join(root, 'toolchain/versions.json'), 'utf8'));
  if (!v.baseImage.includes('@sha256:')) throw new Error('Pin the base first with run tts lock-base');
  return ['docker', 'build', '--platform', v.architecture, '--target', target,
    '--build-arg', `PYTHON_IMAGE=${v.baseImage}`, '--build-arg', `SAFE_CHAIN_VERSION=${chain.safeChain}`,
    '--build-arg', `SAFE_CHAIN_SHA256=${chain.safeChainSha256}`];
}

export async function tts(root: string, args: string[], command: Command) {
  const [action, ...flags] = args;
  const audio = join(root, 'workspace/projects/bluepad/audio');
  if (action === 'firmware' && flags.length <= 1) return firmwareAudio(root, flags[0]);
  if (flags.length) throw new Error('Use run tts lock-base|lock|image|generate');
  if (action === 'lock-base') {
    const path = join(root, 'toolchain/tts/versions.json');
    const v = JSON.parse(await readFile(path, 'utf8'));
    await command(['docker', 'pull', '--platform', v.architecture, v.baseImage]);
    const digests = JSON.parse(await command(['docker', 'image', 'inspect', v.baseImage, '--format', '{{json .RepoDigests}}'], true));
    if (!digests[0]?.includes('@sha256:')) throw new Error('No base image digest');
    v.baseImage = digests[0];
    await writeFile(path, JSON.stringify(v, null, 2) + '\n');
  } else if (action === 'lock') {
    await command([...await buildArgs(root, 'bootstrap'), '-t', bootstrap, join(root, 'toolchain/tts')]);
    const out = join(root, '.cache/tts-lock');
    await rm(out, { recursive: true, force: true });
    await mkdir(out, { recursive: true });
    const mounts = ['--mount', `type=bind,src=${join(root, 'toolchain/tts')},dst=/in,readonly`,
      '--mount', `type=bind,src=${out},dst=/lock`];
    // Resolution downloads and screens artifacts but installs nothing.
    await command(['docker', 'run', ...ttsArgs(root, 'bridge'), ...mounts, bootstrap,
      '/opt/safe-chain/safe-chain', 'pip', 'install', '--dry-run', '--ignore-installed', '--quiet',
      '--report', '/lock/report.json', '--index-url', 'https://download.pytorch.org/whl/cpu',
      '--extra-index-url', 'https://pypi.org/simple', '-r', '/in/requirements.in']);
    const lock = lockFromReport(JSON.parse(await readFile(join(out, 'report.json'), 'utf8')));
    const { voices } = JSON.parse(await readFile(join(audio, 'prompts.json'), 'utf8'));
    const assets = await command(['docker', 'run', ...ttsArgs(root, 'bridge'), ...mounts, bootstrap,
      'python3', '/in/lock.py', 'hexgrad/Kokoro-82M', 'config.json', 'kokoro-v1_0.pth',
      ...voices.map((voice: string) => `voices/${voice}.pt`)], true);
    JSON.parse(assets);
    await writeFile(join(root, 'toolchain/tts/requirements.lock'), lock);
    await writeFile(join(root, 'toolchain/tts/assets.json'), assets + '\n');
  } else if (action === 'image') {
    await command([...await buildArgs(root, 'tts'), '--label', `org.microbit.tts.recipe=${await recipeHash(root)}`,
      '-t', image, join(root, 'toolchain/tts')]);
  } else if (action === 'generate') {
    const metadata = JSON.parse(await command(['docker', 'image', 'inspect', image], true))[0];
    if (metadata.Config.Labels?.['org.microbit.tts.recipe'] !== await recipeHash(root)) {
      throw new Error('TTS image recipe changed; run tts image before generating');
    }
    const out = join(audio, 'candidates');
    await rm(out, { recursive: true, force: true });
    await mkdir(out, { recursive: true });
    await command(['docker', 'run', ...ttsArgs(root, 'none'),
      '--mount', `type=bind,src=${audio},dst=/prompts,readonly`,
      '--mount', `type=bind,src=${out},dst=/out`, metadata.Id]);
  } else throw new Error('Use run tts lock-base|lock|image|generate');
}

import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { createHash } from 'node:crypto';

export function readPcmWav(wav: Buffer) {
  if (wav.length < 44 || wav.toString('ascii', 0, 4) !== 'RIFF' || wav.toString('ascii', 8, 12) !== 'WAVE' || wav.readUInt32LE(4) + 8 !== wav.length)
    throw new Error('Invalid RIFF/WAVE length');
  let rate = 0, pcm: Buffer | undefined;
  for (let p = 12; p + 8 <= wav.length;) {
    const kind = wav.toString('ascii', p, p + 4), size = wav.readUInt32LE(p + 4);
    p += 8;
    if (p + size > wav.length) throw new Error('Truncated WAV chunk');
    if (kind === 'fmt ') {
      if (size < 16 || wav.readUInt16LE(p) !== 1 || wav.readUInt16LE(p + 2) !== 1 || wav.readUInt16LE(p + 14) !== 16 || wav.readUInt16LE(p + 12) !== 2)
        throw new Error('Expected mono signed 16-bit PCM');
      rate = wav.readUInt32LE(p + 4);
    } else if (kind === 'data') pcm = wav.subarray(p, p + size);
    p += size + (size & 1);
  }
  if (rate !== 24000 || !pcm?.length || pcm.length % 2) throw new Error('Expected nonempty 24 kHz PCM');
  return { rate, samples: Float64Array.from({ length: pcm.length / 2 }, (_, i) => pcm!.readInt16LE(i * 2) / 32768) };
}

export function convertPcm(samples: Float64Array, sourceRate = 24000) {
  if (sourceRate !== 24000 || !samples.length || [...samples].some(v => !Number.isFinite(v) || Math.abs(v) > 1)) throw new Error('Invalid PCM');
  // -60 dB threshold, with 100 ms preroll and 120 ms tail. Preserve weak /s/
  // rather than using a speech-energy gate that clips unvoiced consonants.
  const threshold = 0.001;
  let first = samples.findIndex(v => Math.abs(v) >= threshold), last = samples.length - 1;
  if (first < 0) throw new Error('Silent clip');
  while (Math.abs(samples[last]) < threshold) last--;
  first = Math.max(0, first - Math.ceil(sourceRate * 0.1));
  last = Math.min(samples.length, last + 1 + Math.ceil(sourceRate * 0.12));
  const input = samples.subarray(first, last), output = new Float64Array(Math.ceil(input.length * 16000 / sourceRate));
  // Windowed-sinc low-pass resampling, 64 taps, 7.2 kHz cutoff: prevents
  // high-frequency source energy aliasing into the 16 kHz speech stream.
  const cutoff = 7200 / sourceRate;
  for (let i = 0; i < output.length; i++) {
    const position = i * sourceRate / 16000;
    let sum = 0, weight = 0;
    for (let j = Math.ceil(position - 32); j <= Math.floor(position + 32); j++) {
      const distance = j - position;
      const sinc = distance === 0 ? 2 * cutoff : Math.sin(2 * Math.PI * cutoff * distance) / (Math.PI * distance);
      const w = sinc * (0.5 + 0.5 * Math.cos(Math.PI * distance / 32));
      sum += (input[j] ?? 0) * w; weight += w;
    }
    output[i] = sum / weight;
  }
  let peak = 0;
  for (const value of output) peak = Math.max(peak, Math.abs(value));
  const gain = 0.8 / peak;
  const pcm = Uint8Array.from(output, v => Math.max(0, Math.min(255, Math.round(128 + v * gain * 127))));
  return { pcm, first, last, gain };
}

export async function firmwareAudio(root: string, voice = 'af_heart') {
  if (!['af_heart', 'af_bella'].includes(voice)) throw new Error('Voice must be af_heart or af_bella');
  const base = join(root, 'workspace/projects/bluepad');
  const ids = ['speed', 'steering-centre', 'steering-range'];
  const arrays: string[] = [], metadata: object[] = [];
  for (const [index, id] of ids.entries()) {
    const wav = await readFile(join(base, 'audio/candidates', voice, id + '.wav'));
    const { samples, rate } = readPcmWav(wav);
    const { pcm, first, last, gain } = convertPcm(samples, rate);
    const rows = Array.from({ length: Math.ceil(pcm.length / 24) }, (_, row) => '    ' + [...pcm.slice(row * 24, row * 24 + 24)].join(',') + ',');
    arrays.push(`static const uint8_t speech_${index}[] = {\n${rows.join('\n')}\n};`);
    metadata.push({ id, sourceSha256: createHash('sha256').update(wav).digest('hex'), first, last, gain, samples: pcm.length,
      pcmSha256: createHash('sha256').update(pcm).digest('hex') });
  }
  await writeFile(join(base, 'app/speech_data.h'), `// Generated by run tts firmware ${voice}; do not edit.\n#ifndef SPEECH_DATA_H\n#define SPEECH_DATA_H\n#include <stdint.h>\n${arrays.join('\n')}\nstatic const uint8_t *const speech_data[] = {speech_0,speech_1,speech_2};\nstatic const unsigned speech_length[] = {sizeof(speech_0),sizeof(speech_1),sizeof(speech_2)};\n#endif\n`);
  await writeFile(join(base, 'audio/firmware.json'), JSON.stringify({ voice, rate: 16000, format: 'unsigned-8-bit', clips: metadata }, null, 2) + '\n');
  console.log(`Converted ${voice} to app/speech_data.h (16 kHz PCM)`);
}
